"""OpenVR の関数テーブル (openvr_capi.h の VR_IVR*_FnTable) の並びと、構造体の大きさ・位置を、今の Python 版が
使う pyopenvr (1.26.701 = OpenVR 1.26.7) の ctypes の定義から書き出す。

    python native/reference/gen_openvr_tables.py   ->  native/vrct-openvr/src/tables.rs
"""

import ctypes
import re
from pathlib import Path

import openvr

ROOT = Path(__file__).resolve().parents[2]
INTERFACES = ["IVRSystem", "IVROverlay", "IVRCompositor", "IVRApplications", "IVRRenderModels"]
STRUCTS = ["HmdMatrix34_t", "HmdVector2_t", "HmdVector3_t", "TrackedDevicePose_t", "VRControllerState_t", "VREvent_t",
           "Texture_t", "VRTextureBounds_t", "VROverlayIntersectionParams_t", "VROverlayIntersectionResults_t",
           "RenderModel_ComponentState_t", "RenderModel_ControllerMode_State_t"]


def snake(name):
    # getMirrorTextureD3D11 -> GET_MIRROR_TEXTURE_D3D11, getDXGIOutputInfo -> GET_DXGI_OUTPUT_INFO
    return re.sub(r"(?<=[a-z])(?=[A-Z0-9])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).upper()


def main():
    out = ["// Generated by native/reference/gen_openvr_tables.py from pyopenvr "
           f"{openvr.__version__}: do not edit.",
           "//! The function tables of the OpenVR interfaces VRCT uses (index of each function, by its",
           "//! pyopenvr name), and the sizes / field offsets of the structures passed to them.", ""]
    for iface in INTERFACES:
        cls = getattr(openvr, iface + "_FnTable")
        names = [f[0] for f in cls._fields_]
        out.append(f"pub mod {snake(iface[3:]).lower()} {{")
        out.append(f"    pub const VERSION: &str = \"{getattr(openvr, iface + '_Version')}\";")
        out.append(f"    pub const LEN: usize = {len(names)};")
        for i, name in enumerate(names):
            out.append(f"    pub const {snake(name)}: usize = {i};")
        out.append("}")
        out.append("")
    out.append("/// (structure, size, [(field, offset)]) as ctypes lays them out on Windows x64")
    out.append("pub const LAYOUTS: &[(&str, usize, &[(&str, usize)])] = &[")
    for s in STRUCTS:
        c = getattr(openvr, s)
        fields = ", ".join(f"(\"{n}\", {getattr(c, n).offset})" for n, *_ in c._fields_)
        out.append(f"    (\"{s}\", {ctypes.sizeof(c)}, &[{fields}]),")
    out.append("];")
    path = ROOT / "native" / "vrct-openvr" / "src" / "tables.rs"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(("\n".join(out) + "\n").encode("utf-8"))
    print(path)


if __name__ == "__main__":
    main()
