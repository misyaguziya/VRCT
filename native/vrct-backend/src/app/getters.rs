//! The getters that return a setting as it is (controller.py's _SIMPLE_CONFIG_GETTERS).
use super::App;
use crate::ipc::Reply;
use serde_json::Value;

macro_rules! getters {
    ($($name:ident => $attr:literal),* $(,)?) => {
        $(pub fn $name(app: &App, _: Option<Value>) -> anyhow::Result<Reply> {
            Ok(Reply::ok(app.config.get($attr)))
        })*
    };
}

